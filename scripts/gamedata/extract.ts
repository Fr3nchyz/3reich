/**
 * Regenerates src/data/gamedata.ts from the original game's files and prints a short report.
 *
 *   npx vite-node scripts/gamedata/extract.ts <game-folder>
 *
 * The game folder stays outside the repository. Only derived facts are written: the hex ids each
 * control bitmap marks and the hexsides each line runs along. See docs/GAME_DATA.md.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { MAP } from "../../src/data/map";
import { decodeBitmap, decodeLine, lineEnds, lineHexsides, MASK_DIRECTIONS, type LineEntry } from "./formats";

/** Control bitmaps: territory at the start of a scenario, or a region the rules name. */
const BITMAPS = ["BRIT42", "BRIT44", "EASTEURP", "GERM42", "GERM44", "ITALY42", "USSR42", "USSR44", "VICHY", "VICHY42"] as const;
/** Line files: the Polish Partition Line and the 1942 and 1944 scenario start lines. */
const LINES = ["NSPPLINE", "1942LINE", "1944LINE"] as const;

const folder = process.argv[2];
if (!folder) {
  console.error("usage: npx vite-node scripts/gamedata/extract.ts <game-folder>");
  process.exit(1);
}
const read = (name: string) => new Uint8Array(readFileSync(join(folder, name)));

const bitmaps = Object.fromEntries(BITMAPS.map((b) => [b, decodeBitmap(read(`${b}.CON`))]));
const lineEntries = Object.fromEntries(LINES.map((l) => [l, decodeLine(read(`${l}.BIN`))])) as Record<string, LineEntry[]>;
const lines = Object.fromEntries(LINES.map((l) => [l, lineHexsides(lineEntries[l]!)]));

// --- report -------------------------------------------------------------------------------
for (const b of BITMAPS) {
  const byCountry = new Map<string, number>();
  const notLand: string[] = [];
  for (const id of bitmaps[b]!) {
    const h = MAP.hexes[id];
    if (!h?.land) notLand.push(id);
    else byCountry.set(h.country!, (byCountry.get(h.country!) ?? 0) + 1);
  }
  const countries = [...byCountry].sort().map(([c, n]) => `${c} ${n}`).join(", ");
  console.log(`${b}.CON: ${bitmaps[b]!.length} hexes (${countries})${notLand.length ? `; not land on our map: ${notLand.join(" ")}` : ""}`);
}
// Bits 3 and 4 of a line mask cannot be told apart by contiguity alone: show the other reading too.
const swapped = (entries: LineEntry[]) =>
  entries.map((e) => ({ ...e, directions: e.directions.map((d) => (d === MASK_DIRECTIONS[3] ? MASK_DIRECTIONS[4]! : d === MASK_DIRECTIONS[4] ? MASK_DIRECTIONS[3]! : d)) }));
for (const l of LINES) {
  const hexsides = lines[l]!;
  let other: string;
  try {
    other = `${lineEnds(lineHexsides(swapped(lineEntries[l]!)))}`;
  } catch {
    other = "off the map";
  }
  console.log(`${l}.BIN: ${lineEntries[l]!.length} entries, ${hexsides.length} hexsides, ${lineEnds(hexsides)} loose ends (${other} with bits 3 and 4 swapped)`);
}

// --- output -------------------------------------------------------------------------------
const wrap = (ids: readonly string[], indent: string) => {
  const out: string[] = [];
  let line = "";
  for (const id of ids.map((i) => `"${i}",`)) {
    if (line && line.length + id.length + 1 > 120 - indent.length) {
      out.push(indent + line);
      line = "";
    }
    line += (line ? " " : "") + id;
  }
  if (line) out.push(indent + line);
  return out.join("\n");
};
const record = (name: string, doc: string, type: string, entries: Record<string, readonly string[]>, file: (k: string) => string) =>
  [
    doc,
    `export const ${name}: Readonly<Record<${Object.keys(entries).map((k) => `"${k}"`).join(" | ")}, readonly ${type}[]>> = {`,
    ...Object.entries(entries).map(([k, ids]) => `  // ${file(k)}: ${ids.length}\n  ${/^\d/.test(k) ? `"${k}"` : k}: [\n${wrap(ids, "    ")}\n  ],`),
    "};",
  ].join("\n");

const text = `// Generated by scripts/gamedata/extract.ts from the original game's files. Do not edit by hand.
// Facts derived from the files (hex ids and hexsides in our coordinates), not the files themselves.
// See docs/GAME_DATA.md for the formats.
import type { HexId, HexsideId } from "../engine/hex";

${record(
  "CONTROL_BITMAPS",
  "/** Every hex each control bitmap marks, in file order. Some are sea or coastal slivers on our map. */",
  "HexId",
  bitmaps,
  (k) => `${k}.CON`,
)}

${record("LINE_HEXSIDES", "/** The hexsides each line runs along, sorted. */", "HexsideId", lines, (k) => `${k}.BIN`)}
`;
const target = fileURLToPath(new URL("../../src/data/gamedata.ts", import.meta.url));
writeFileSync(target, text);
console.log(`wrote ${target}`);
